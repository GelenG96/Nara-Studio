enum class EditorFontChoice(val key: String, val label: String, val fontFamily: FontFamily) {
    LITERATA("LITERATA", "Literata (Sastra)", LiterataFontFamily),
    MERRIWEATHER("MERRIWEATHER", "Merriweather (Klasik)", MerriweatherFontFamily),
    LORA("LORA", "Lora (Novel)", LoraFontFamily),
    PLUS_JAKARTA("PLUS_JAKARTA", "Plus Jakarta Sans", PlusJakartaSansFontFamily),
    JETBRAINS_MONO("JETBRAINS_MONO", "JetBrains Mono", JetBrainsMonoFontFamily);

    companion object {
        fun fromKey(key: String?): EditorFontChoice =
            entries.firstOrNull { it.key == key } ?: LITERATA
    }
}

